const DICT = LANG === 'en' ? EN : LANG === 'ja' ? JA : null;

/** tx('ทำงานมา {0}', '3 วัน') → the text in the chosen language with {0}, {1} … filled in */
export function tx(text, ...args) {
  const out = DICT?.[text] ?? text;
  return args.length ? out.replace(/\{(\d)\}/g, (_, i) => String(args[i])) : out;
}

/** every view builds its text when it renders, so a new language takes a reload */
export function setLang(lang) {
  if (!Object.hasOwn(LANGS, lang) || lang === LANG) return;
  write('dock.lang', lang);
  location.reload();
}

export const theme = () => (THEMES.includes(read('dock.theme')) ? read('dock.theme') : 'system');
/** system follows the OS; light / dark pin it (html[data-theme], see style.css). Charts redraw on 'dock-theme'. */
export function setTheme(t) {
  if (!THEMES.includes(t)) return;
  write('dock.theme', t);
  if (t === 'system') delete document.documentElement.dataset.theme;
  else document.documentElement.dataset.theme = t;
  window.dispatchEvent(new Event('dock-theme'));
}
